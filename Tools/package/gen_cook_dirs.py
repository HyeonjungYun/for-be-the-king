"""Writes the always-cook block of S1/Config/DefaultGame.ini (2026-10-18, first playtest package).

The client loads some assets by path at runtime - the cooker cannot see those references, so a packaged build would
miss them:
  - every AnimSequence in S1/Content/Data/anim_clips.csv (S1AnimCatalog, TryLoad)
  - /Game/FX/M_S1SwordWave (S1ProjectileSubsystem) · /Game/Level/M_S1Sea (S1CampScenery) · /Engine/BasicShapes (LoadObject)
The animation packs are ~9 GB, so only the folders that hold a listed clip are cooked, not the whole packs.

Usage:  python Tools/package/gen_cook_dirs.py           rewrite the block
        python Tools/package/gen_cook_dirs.py --check   exit 1 if the block is stale (Tools/package/package-client.ps1 runs this)
"""
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
INI = os.path.join(ROOT, 'S1', 'Config', 'DefaultGame.ini')
CLIPS = os.path.join(ROOT, 'S1', 'Content', 'Data', 'anim_clips.csv')

BEGIN = '; >>> cook-dirs (generated by Tools/package/gen_cook_dirs.py - do not edit by hand)'
END = '; <<< cook-dirs'

# Loaded by path in code, or referenced only from config (GameInstanceClass) - small folders, cooked whole
FIXED = ['/Game/Blueprints', '/Game/Input', '/Game/FX', '/Game/Level', '/Engine/BasicShapes']


def clip_dirs():
    with open(CLIPS, encoding='utf-8-sig', newline='') as f:
        rows = list(csv.reader(f))
    col = rows[0].index('asset')
    dirs = set()
    for r in rows[1:]:
        if len(r) > col and r[col].strip():
            path = r[col].strip().split('.')[0]
            dirs.add(path.rsplit('/', 1)[0])
    return sorted(dirs)


def block(nl):
    lines = [BEGIN, '[/Script/UnrealEd.ProjectPackagingSettings]', '+MapsToCook=(FilePath="/Game/Maps/Floor1")']
    lines += ['+DirectoriesToAlwaysCook=(Path="%s")' % d for d in FIXED + clip_dirs()]
    lines.append(END)
    return nl.join(lines)


def main():
    raw = open(INI, 'rb').read()
    text = raw.decode('utf-8')
    nl = '\r\n' if text.count('\r\n') * 2 > text.count('\n') else '\n'
    new_block = block(nl)

    if BEGIN in text:
        start = text.index(BEGIN)
        end = text.index(END, start) + len(END)
        updated = text[:start] + new_block + text[end:]
    else:
        updated = text.rstrip('\r\n') + nl + nl + new_block + nl

    if '--check' in sys.argv:
        if updated != text:
            print('[COOK] DefaultGame.ini cook-dirs block is stale - run python Tools/package/gen_cook_dirs.py')
            return 1
        print('[COOK] cook-dirs block is current (%d clip folders)' % len(clip_dirs()))
        return 0

    if updated != text:
        open(INI, 'wb').write(updated.encode('utf-8'))
        print('[COOK] wrote %d clip folders + %d fixed' % (len(clip_dirs()), len(FIXED)))
    else:
        print('[COOK] unchanged')
    return 0


if __name__ == '__main__':
    sys.exit(main())
